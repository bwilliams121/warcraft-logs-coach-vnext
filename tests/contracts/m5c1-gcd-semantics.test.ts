function filesUnder(root: string): readonly string[] {
  if (!existsSync(root)) return [];
  return readdirSync(root, { recursive: true, withFileTypes: false })
    .map((entry) => `${root}/${String(entry).replace(/\\/g, "/")}`)
    .filter((path) => statSync(path).isFile() && path.endsWith(".ts"));
}

/**
 * Source with comments stripped.
 *
 * Same convention as `m5-boundary-and-vocabulary.test.ts`: the prohibition is on
 * CODE, and a doc comment must stay free to NAME the thing it forbids. The
 * scoped-selection header explains why `GLOBAL_APL` is absent, and that
 * explanation is the opposite of a violation.
 */
function codeOf(path: string): string {
  return readFileSync(path, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
}

/**
 * Source with comments AND string literals stripped.
 *
 * What is left is code that DOES something. Used where the prohibition is on
 * USING a value rather than on mentioning one: an identity number quoted inside
 * a `finding:` string is a human saying which DBC row they read, and removing it
 * would make the reading unverifiable.
 */
function codeWithoutStrings(path: string): string {
  return codeOf(path)
    .replace(/"(?:[^"\\\n]|\\.)*"/g, '""')
    .replace(/'(?:[^'\\\n]|\\.)*'/g, "''")
    .replace(/`(?:[^`\\]|\\.)*`/g, "``");
}

