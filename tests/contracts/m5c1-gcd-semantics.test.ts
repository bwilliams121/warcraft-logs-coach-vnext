describe("M5-A and M5-B are untouched by execution lane", () => {
  it("adds no execution lane to any finding, judgment or selection type", () => {
    // Lane information exists; it is deliberately not plumbed into a committed
    // M5-A/M5-B result shape.
    //
    // NARROWED AT M5-C3c3b by exactly one file. The first-GCD rescan engine's
    // whole terminal test is "is the selected action GCD-consuming", so it
    // necessarily handles the lane — but it takes it as an INPUT from a
    // caller-supplied resolver and stores it in no result, which is asserted
    // directly below. Every other module in both trees is still forbidden it.
    const exempt = "src/simc/first-gcd-selection.ts";
    for (const path of [...filesUnder("src/findings"), ...filesUnder("src/simc")]) {
      if (path === exempt) continue;
      const code = codeOf(path);
      expect(code, `${path} mentions executionLane`).not.toContain("executionLane");
      expect(code, `${path} mentions ExecutionLane`).not.toContain("ExecutionLane");
    }
  });

  it("keeps the lane an INPUT to the rescan engine, never a field of its results", () => {
    // The claim the narrowing above rests on. A lane stored in a result would be
    // a committed shape carrying derived GCD semantics, which is the thing the
    // original rule exists to prevent; a lane consumed and discarded is not.
    const code = codeOf("src/simc/first-gcd-selection.ts");
    expect(code).toContain("laneFor");
    // Declared once, as the resolver's return type, and nowhere else.
    expect(code.match(/ExecutionLane/g) ?? []).toHaveLength(2);
    expect(code).not.toContain("executionLane");
    // A field literally named `lane`. `readonly laneFor:` is the RESOLVER and is
    // exactly what this test is confirming, so the check is anchored rather than
    // a substring that would trip over it.
    expect(/readonly lane\s*[?:]/.test(code)).toBe(false);
  });

  it("keeps the lane out of every traversal result shape", () => {
    // Positive form of the same rule: C3b's committed step and result types are
    // what M5-B consumers see, and neither gained a lane.
    const code = codeOf("src/simc/nested-selection.ts");
    expect(code).not.toContain("Lane");
    expect(code).not.toContain("ability-gcd-semantics");
  });

  it("keeps the scoped-selection producer free of GCD semantics", () => {
    const code = codeOf("src/specs/rogue/assassination/spend-selection.ts");
    expect(code).not.toContain("ability-gcd-semantics");
    expect(code).not.toContain("rotational-slot");
  });

  it("keeps lane semantics out of the ordered selector", () => {
    // C1 is structural semantics, not traversal. The selector is the one module
    // a lane-aware change would most plausibly creep into.
    const code = codeOf("src/simc/list-selection.ts");
    expect(code).not.toContain("entryKind");
    expect(code).not.toContain("Lane");
    expect(code).not.toContain("Gcd");
  });

  it("does not stage a global selection family", () => {
    // M5-C1 establishes eligibility. Global traversal is a later step, and its
    // vocabulary must not appear before it can be supported.
    for (const path of filesUnder("src")) {
      const code = codeOf(path);
      for (const forbidden of [
        "GlobalAplSelection",
        "GlobalThroughputSelection",
        "selectGlobally",
        "GLOBAL_APL",
      ]) {
        expect(code, `${path} declares ${forbidden}`).not.toContain(forbidden);
      }
    }
  });

  it("introduces no negative ACTIONABILITY state", () => {
    // UNCHANGED IN SUBSTANCE, NARROWED IN WORDING, at M5-C3c2.
    //
    // The claim this test has always made is in its title: ACTIONABILITY — the
    // finding-layer judgment about whether a decision was possible in the
    // encounter — admits no negative member. It still does not. The two-member
    // vocabulary is asserted at its source in m5b-scope-and-actionability.
    //
    // It USED to enforce that by banning the string "PROVEN_UNUSABLE" from all
    // of src/. That was a proxy, and M5-C3c2 legitimately breaks the proxy:
    // negative USABILITY is now a real, evidence-backed verdict about whether
    // SimulationCraft's ready() could have succeeded. Usability is not
    // actionability, and C3c1's own regression test records the handover
    // ("That is C3c2's job").
    //
    // The proxy is replaced by the invariant that actually protects the
    // distinction: a negative usability verdict cannot be produced ANYWHERE
    // except through a constructor that demands evidence.
    const declaring = filesUnder("src").filter((path) => codeOf(path).includes('kind: "PROVEN_UNUSABLE"'));
    expect(declaring).toEqual(["src/simc/action-applicability.ts"]);

    // Nowhere in src/ does actionability vocabulary acquire a negative member.
    for (const path of filesUnder("src")) {
      const code = codeOf(path);
      expect(code, `${path} declares NOT_ACTIONABLE`).not.toContain("NOT_ACTIONABLE");
      expect(code, `${path} declares PROVEN_NOT_ACTIONABLE`).not.toContain("PROVEN_NOT_ACTIONABLE");
    }
  });

  it("introduces no coaching category vocabulary", () => {
    // Execution lane has versioned provenance. A coaching category does not yet
    // have an evidence standard, so the vocabulary stays out.
    for (const path of filesUnder("src")) {
      const code = codeOf(path);
      for (const forbidden of [
        "coachingCategory",
        '"THROUGHPUT"',
        '"UTILITY"',
        '"SURVIVAL"',
        '"NOT_COACHED"',
      ]) {
        expect(code, `${path} declares ${forbidden}`).not.toContain(forbidden);
      }
    }
  });
});

