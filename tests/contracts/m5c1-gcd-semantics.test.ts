describe("two kinds of knowledge, never confused", () => {
  /**
   * The artifact carries a machine-extracted half and a hand-reviewed half:
   *
   *     spell id -> baseGcdMs           parsed from the generated DBC table
   *     token    -> candidate spell ids read out of C++ control flow by a human
   *
   * Nothing in this project parses C++. These assertions exist so the artifact
   * can never present the second as though it were the first.
   */

  it("labels the ability half as machine-extracted", () => {
    if (!loaded.ok) return;
    expect(loaded.artifact.provenance.abilityDataMethod).toBe(MACHINE_EXTRACTED_METHOD);
    expect(loaded.artifact.provenance.gcdFieldName).toBe("_gcd");
  });

  it("labels EVERY token binding as hand-reviewed C++ control flow", () => {
    if (!loaded.ok) return;
    expect([...TOKEN_BINDING_METHODS]).toEqual(["HAND_REVIEWED_CPP_CONTROL_FLOW"]);
    for (const { simcToken, binding } of loaded.artifact.tokenBindings) {
      expect(binding.method, simcToken).toBe("HAND_REVIEWED_CPP_CONTROL_FLOW");
    }
  });

  it("makes a machine-extracted binding claim unrepresentable", () => {
    // Not merely absent from the data — absent from the vocabulary, so a future
    // edit cannot promote a hand-reviewed reading by changing one string.
    expect(TOKEN_BINDING_METHODS as readonly string[]).not.toContain(MACHINE_EXTRACTED_METHOD);
  });

  it("hashes sc_rogue.cpp as a source WITHOUT parsing it", () => {
    // The binding hash must be MEASURED from the file, not transcribed, or the
    // hand-reviewed reading is not reproducible. It appears in `sources` for
    // that reason, and the extractor never parses it.
    if (!loaded.ok) return;
    const rogueModule = loaded.artifact.provenance.sources.find(
      (source) => source.path === ROGUE_MODULE_PATH,
    );
    expect(rogueModule?.sha256).toBe(ROGUE_MODULE_SHA256);
    expect(rogueModule?.byteLength).toBeGreaterThan(0);

    const extractor = readFileSync("scripts/authority/extract-simc-gcd.mjs", "utf8");
    expect(extractor).toContain("NEVER PARSED");
  });

  it("binds every candidate id to a real machine-extracted record", () => {
    // The load-bearing join between the two halves: the hand-reviewed side can
    // never introduce a spell the generated DBC data does not carry.
    if (!loaded.ok) return;
    const extractedIds = new Set(loaded.artifact.abilities.map((entry) => entry.abilityGameId));
    for (const { simcToken, candidateAbilityGameIds } of loaded.artifact.tokenBindings) {
      for (const candidate of candidateAbilityGameIds) {
        expect(extractedIds.has(candidate), `${simcToken} -> ${String(candidate)}`).toBe(true);
        expect(baseGcdMsForAbility(candidate), `${simcToken} -> ${String(candidate)}`).not.toBeNull();
      }
    }
  });

  it("rejects an artifact whose binding claims to be machine-extracted", () => {
    const draft = JSON.parse(JSON.stringify(artifact)) as Record<string, unknown>;
    const bindings = draft["tokenBindings"] as { binding: Record<string, unknown> }[];
    bindings[0]!.binding["method"] = MACHINE_EXTRACTED_METHOD;
    const result = validateGcdSemanticsArtifact(draft);
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.reason).toBe("MALFORMED_BINDING_PROVENANCE");
  });

  it.each([
    "method",
    "sourcePath",
    "sourceSha256",
    "symbol",
    "startLine",
    "endLine",
    "sourceNote",
    "crossCheck",
  ])("rejects an artifact whose binding omits %s", (field) => {
    const draft = JSON.parse(JSON.stringify(artifact)) as Record<string, unknown>;
    const bindings = draft["tokenBindings"] as { binding: Record<string, unknown> }[];
    delete bindings[0]!.binding[field];
    expect(validateGcdSemanticsArtifact(draft).ok).toBe(false);
  });

  it("rejects an artifact whose ability half is not labelled machine-extracted", () => {
    const draft = JSON.parse(JSON.stringify(artifact)) as Record<string, unknown>;
    (draft["provenance"] as Record<string, unknown>)["abilityDataMethod"] = "HAND_REVIEWED_CPP_CONTROL_FLOW";
    expect(validateGcdSemanticsArtifact(draft).ok).toBe(false);
  });
});

